-- Один лимит на пару «счёт + категория + момент установки».
--
-- LimitAnalyticsQueryRepository находит действующий лимит джойном по значению момента:
-- l.limit_datetime = (SELECT MAX(inner_l.limit_datetime) ...). Два лимита с одинаковым limit_datetime
-- удовлетворяли бы этому условию оба, и одна превышенная транзакция вернулась бы в
-- GET /limits/exceeded двумя строками — с разными limit_sum, если суммы не совпадают. Клиент увидел бы
-- превышение дважды и не смог бы понять, какой лимит считать превышенным.
--
-- Ограничение делает максимум единственным, поэтому джойн одно-значен по построению, а не по
-- соглашению. Тот же смысл проверяет LimitCommandService: он берёт блокировку периода и отказывает с
-- 409, если лимит на этот момент уже установлен, поэтому ограничение — страховка от гонки и от
-- записи в обход сервиса, а не основной путь проверки.
--
-- Индекс ix_expense_limit_lookup (account_from, expense_category, limit_datetime DESC) покрывал тот же
-- предикат, поэтому он удалён: уникальное ограничение создаёт индекс по тем же трём колонкам в
-- возрастающем порядке, а запросы выборки лимитов читают его в обратном направлении. Два индекса на
-- одних и тех же колонках — лишняя запись при каждом новом лимите.
--
-- Если в развёрнутой БД такие дубли уже есть, их нужно предварительно слить вручную: удаление
-- строк молча выбросило бы часть истории лимитов, а ON CONFLICT скрыл бы исходные суммы.
ALTER TABLE expense_limit
    ADD CONSTRAINT uc_expense_limit_instant
    UNIQUE (account_from, expense_category, limit_datetime);

DROP INDEX ix_expense_limit_lookup;