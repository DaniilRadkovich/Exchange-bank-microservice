--changeset exchange:004-amount-usd-precision
-- Сумма в USD шире суммы в валюте операции: amount_usd есть произведение amount на курс, а не сумма
-- сама по себе.
--
-- NUMERIC(19, 2) хватает amount (17 знаков целых плюс два после точки), но не amount_usd: при курсе
-- выше единицы произведение выходит за 17 знаков целых, и PostgreSQL отвечает «numeric field
-- overflow». Транзакция при этом принималась — sum проходит @Digits(integer = 17), а это проверка
-- формата, а не смысла значения, — расчёт падал на записи, и после исчерпания попыток она уходила
-- в FAILED. Данные банка оказывались несохранимыми из-за узкой колонки.
--
-- Ширины подобраны так, чтобы переполнение было невозможно при любых значениях, которые схема
-- принимает:
--   amount      NUMERIC(19, 2)   < 10^17  та же граница, что и @Digits(integer = 17) на DTO;
--   usd_rate    NUMERIC(19, 10)  < 10^9   в расчёт попадает только курс, прошедший запись
--                                         в exchange_rate, а больший отвергается самой колонкой;
--   amount_usd = amount x usd_rate < 10^26, а NUMERIC(30, 2) вмещает < 10^28.
-- Сужать amount_usd обратно к NUMERIC(19, 2) нельзя: это снова сделает часть принятых транзакций
-- несохранимыми, и отвергать их на приёме нельзя — это потеря данных.
--
-- Расширение типа безопасно для уже сохранённых данных: 001 объявляет amount_usd NUMERIC(19, 2),
-- поэтому существующие значения влезают в новую ширину. Миграция ничего не округляет, не отвергает
-- и не блокирует таблицу дольше обычного ALTER.

ALTER TABLE expense_transaction
    ALTER COLUMN amount_usd TYPE NUMERIC(30, 2);

COMMENT ON COLUMN expense_transaction.amount_usd IS 'Сумма операции в USD: amount × usd_rate. Колонка шире amount, потому что это произведение, а курс выше единицы добавляет знаки целой части.';
