--changeset exchange:003-rate-precision
-- Курс валюты хранится с 10 знаками после точки вместо четырёх.
--
-- Четыре знака непригодны для реальных курсов к USD: курс казахстанского тенге около 0.0025, поэтому
-- округление HALF_UP до четырёх знаков отбрасывает до 0.5% курса, и сумма операции считается по
-- искажённой цене. Конкретные примеры, которые пришли из пробы на реальном стеке:
--   0.00251234 -> 0.0025, 10000.00 KZT -> 25.00 USD вместо 25.12 (недобор 0.12 USD);
--   0.00006180 (IDR) -> 0.0001, 1000000.00 IDR -> 100.00 USD вместо 61.80 (завышение 38 USD).
--
-- Хуже того, курс мельче половины последнего разряда обнулялся совсем: 0.0000391 (VND) становился
-- 0.0000, а колонка с ограничением close_rate > 0 отвергала такую запись. Транзакция оставалась
-- PENDING, после исчерпания попыток уходила в FAILED и больше никогда не дорассчитывалась — то есть
-- валюта становилась нерасчётной навсегда, а в логе причина выглядела как отказ внешнего API.
--
-- 10 знаков покрывают и VND/IDR/KRW (0.0000397, 0.0000618, 0.00000072), и пары с курсом выше единицы;
-- 9 знаков до запятой остаётся с большим запасом, колонка по-прежнему NUMERIC, а не double.
-- Суммы не трогаются: amount и amount_usd остаются NUMERIC(19, 2).
--
-- Про развёрнутую БД: PostgreSQL переписывает таблицу целиком под ACCESS EXCLUSIVE, потому что
-- NUMERIC(19, 4) и NUMERIC(19, 10) не бинарно совместимы. Миграцию нужно выполнять в окно
-- обслуживания. Уже сохранённые курсы останутся с четырьмя знаками — точность, потерянная при
-- прежнем округлении, не восстанавливается переносом типа. Если её нужно вернуть, курсы придётся
-- запросить заново (DELETE FROM exchange_rate), а это платные обращения к внешнему API; решение
-- остаётся за оператором, автоматически удалять кэш эта миграция не станет.

ALTER TABLE exchange_rate
    ALTER COLUMN close_rate TYPE NUMERIC(19, 10),
    ALTER COLUMN previous_close TYPE NUMERIC(19, 10);

ALTER TABLE expense_transaction
    ALTER COLUMN usd_rate TYPE NUMERIC(19, 10);
